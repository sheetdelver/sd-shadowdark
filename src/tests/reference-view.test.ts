import assert from 'node:assert/strict';
import { prepareReferenceView } from '../server/reference-view';
import { presentReferenceDescription, presentDescription } from '../logic/description';
const runtime = { signal: new AbortController().signal };
const source = { _id: 'original', type: 'NPC', name: 'Reference Monster', img: 'icons/svg/cowled.svg', system: { attributes: { hp: { value: 20, max: 20 }, ac: { value: 14 } }, abilities: {}, level: { value: 3 }, description: '[[/r 1d6]]' }, items: [], effects: [] };
const context = { uuid: 'Compendium.shadowdark.monsters.Actor.original', documentType: 'Actor' as const, document: source };
const before = structuredClone(source);
const result = await prepareReferenceView(context, runtime);
assert.equal(result?.title, 'Reference Monster');
assert.deepEqual(result?.model.actions, []);
assert.deepEqual(source, before);
assert.ok(result?.model.facts.some(fact => fact.label === 'HP' && String(fact.value).includes('20')));
assert.equal(await prepareReferenceView({ ...context, document: { ...source, type: 'Player' } }, runtime), null);
assert.equal(await prepareReferenceView({ ...context, uuid: 'Actor.original' }, runtime), null);
assert.equal(await prepareReferenceView({ ...context, documentType: 'Item' }, runtime), null);
const item = await prepareReferenceView({ uuid: 'Compendium.shadowdark.gear.Item.sword', documentType: 'Item', document: { name: 'Sword', type: 'Weapon', system: {} } }, runtime);
assert.equal(item?.title, 'Sword'); assert.deepEqual(item?.model.actions, []);
const rich = '@UUID[Compendium.shadowdark.gear.Item.sword]{Sword} [[/r 1d6]] [[check 12 str]] <button>Use</button> <a href="https://example.org">external</a>';
assert.match(presentDescription(rich), /<button/);
const inert = presentReferenceDescription(rich);
assert.doesNotMatch(inert, /<(button|a|input|form|select|textarea)\b|data-action|data-uuid/);
assert.match(inert, /roll 1d6/); assert.match(inert, /check STR/); assert.match(inert, /Sword/);
const abort = new AbortController(); abort.abort();
assert.equal(await prepareReferenceView(context, { signal: abort.signal }), null);
console.log('PASS: exact NPC/Item sources, no actions or mutations, older-host fallback, aborted work, inert rich text');
